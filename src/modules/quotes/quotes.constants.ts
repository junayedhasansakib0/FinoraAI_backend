/**
 * Constants for the motivational-quote card (ARCHITECTURE.md §3, §7; D11/D12). The card is
 * decorative: it shows one short, original, finance-relevant reminder on the Transactions, Budgets
 * and Goals pages. Everything the feature needs — the categories, the fixed system prompt, the
 * curated fallback lines, the cache windows and the dedicated quota key — is gathered here so the
 * service and validation layers stay thin.
 *
 * Nothing here is built from user input: the only per-request variable is the category (an enum) and
 * the small recent-quote history the service feeds back to avoid repeats (R-I3). No user data ever
 * reaches the model (R-I1) — quotes are generic public text, which is why one cached line per
 * category can be shared across every user (D11).
 */

/** The only three sections that carry the card. Also the enum the route validates against. */
export const QUOTE_CATEGORIES = ['transactions', 'budgets', 'goals'] as const;

export type QuoteCategory = (typeof QUOTE_CATEGORIES)[number];

/** The wire shape `GET /quotes/:category` returns; `source` tells the client which line it got. */
export interface QuoteResult {
  quote: string;
  category: QuoteCategory;
  source: 'ai' | 'fallback';
  disclaimer: string;
}

/**
 * What each section's quote should be *about*. Fed to the model as guidance, never shown to the
 * user. Kept general and finance-relevant so a generated line always fits the page it sits on.
 */
