/** The one disclaimer text, carried in the API payload and the card's accessible label only (R-I5). */
export const QUOTE_DISCLAIMER =
  'A general motivational reminder generated by AI — for encouragement only, not financial advice.';

/**
 * How long a generated line is served before a refresh is attempted (~12h), and how long past that
 * a stale line may still be served while a refresh runs (~another 12h → ~24h total). Rotating on
 * this cadence keeps app-wide generation at ~6 calls/day across the three sections (D11, §8).
 */
export const QUOTE_CACHE_FRESH_MS = 12 * 60 * 60 * 1000;
export const QUOTE_CACHE_STALE_MS = 12 * 60 * 60 * 1000;

/** How many recent quotes per category are fed back to the model so it does not repeat itself. */
export const QUOTE_HISTORY_SIZE = 10;

/** Word bounds for a generated line. A little slack around the documented ~8–25 so a good line is
 *  not rejected for a word or two, while a runaway response is still capped (R-I4). */
export const QUOTE_WORD_MIN = 5;
export const QUOTE_WORD_MAX = 30;

/** A hard character cap on the quote, independent of word count, to bound abusive output (R-I4/R-B8). */
export const QUOTE_TEXT_MAX_CHARS = 240;

/**
 * The dedicated quota key passed to the AI Service for every quote generation (D12). It buckets the
 * best-effort per-"user" AI quota (R-I6) under one fixed sentinel, so decorative generation can
 * never deplete a real user's 15/hr·50/day financial-AI budget. The model never sees this string and
 * it never reaches Prisma (R-I1).
 */
export const QUOTE_QUOTA_KEY = 'motivational-quotes';

/**
 * The fixed, server-side system prompt for quote generation (R-I3). It states the rules a line must
 * follow — length, originality, finance-relevance, and the hard "no advice / no guarantees / no
 * attributions / no fake statistics / no guilt" bans — and pins the JSON output shape (R-I4). It is
 * a constant: no user free-text is ever interpolated into it.
 */
export const QUOTE_SYSTEM_PROMPT = [
  "You write one short, original motivational line for Finora, a personal-finance app.",
  `The line must be between ${String(QUOTE_WORD_MIN)} and ${String(QUOTE_WORD_MAX)} words — ideally 8 to 25 — concise, warm, and natural to read.`,
  'It must be relevant to personal finance and to the specific section named in the request. Do not write a generic, non-financial quote.',
  'Write your own original line. Do NOT quote, attribute, or imitate any real person, book, or famous saying, and never add an author or source.',
  'Never promise or guarantee any financial outcome, give investment, tax, or legal advice, cite any statistic or number, or use guilt, shame, or fear.',
  'Keep it encouraging and inclusive. Avoid clichés and avoid repeating any of the recent lines you are shown.',
  'Reply with ONLY a single JSON object of the form {"quote": "...", "category": "..."} — no markdown, no code fences, and no text before or after the JSON.',
].join('\n');

/**
 * Build the user message for one generation: the section, its topic guidance, and the recent lines
 * to avoid. Pure and side-effect-free; the recent list is generic public text, never user data.
 */
export function buildQuoteUserPrompt(category: QuoteCategory, recent: readonly string[]): string {
  const lines = [
    `Section: ${category}.`,
    `Write a line about: ${QUOTE_TOPICS[category]}.`,
    'Return that exact section string in the "category" field.',
  ];

  if (recent.length > 0) {
    lines.push('Do not repeat or closely paraphrase any of these recent lines:');
    for (const line of recent) {
      lines.push(`- ${line}`);
    }
  }

  return lines.join('\n');
}

